"""Generate the flipzone combo family: near-strike lottery + distance-gated chaser.

One metric — |BTC - strike| as % (abs_btc_distance_to_price_to_beat_pct) —
splits every market moment into:

  * flip zone  (dist <= 0.05): buy the crashed side cheap (near-strike lottery;
    win rate 10-24% vs 2.5% breakeven, threshold swept and confirmed optimal —
    all in-sample winners sit <= 0.049, next one at 0.177)
  * decided zone (dist >= 0.05): back the leader (distance-gated chaser; best
    no-lottery supporter, 10/10 positive groups on all 320 markets)

This generator sweeps HOW MUCH of the effective balance each side gets
(lottery_pct / chaser main pool = 1 - lottery_pct), plus one per_rule-cooldown
variant (the chaser fires often; under global cooldown that can delay lottery
tickets by a few ticks).

Rule order: take-profits, then lottery (rare matches, can't spam-block), then
chaser legs.

Usage:
    python scripts/simulation/generate_flipzone_combo_configs.py
"""

from pathlib import Path

OUTPUT_DIR = Path("configs/strategies/flipzone_combo")

FLIP_ZONE_DIST_PCT = 0.05
LOTTERY_SPLITS = (0.20, 0.35, 0.50, 0.65, 0.80)
PER_RULE_VARIANT_SPLIT = 0.50


def build_config(name: str, lottery_pct: float, cooldown_scope: str = "global") -> str:
    chaser_pct = round(1.0 - lottery_pct, 6)
    scope_line = f"  cooldown_scope: {cooldown_scope}\n" if cooldown_scope != "global" else ""
    return f"""name: flipzone_{name}
type: rule_based
starting_balance: 100
order_usd: 1

# Auto-generated by scripts/simulation/generate_flipzone_combo_configs.py
# Near-strike lottery ({lottery_pct:.0%} of effective balance) + distance-gated
# chaser ({chaser_pct:.0%}). Flip-zone boundary: {FLIP_ZONE_DIST_PCT}% distance to strike.

params:
  default_usd_amount: 1
  max_orders: 200
  cooldown_ticks: 3
{scope_line}
  pools:
    lottery:
      max_pool_spend_pct: {lottery_pct}
    main:
      max_pool_spend_pct: {chaser_pct}

  rules:
    - name: take_profit_up_position
      all:
        - metric: has_up_position
          operator: "is"
          value: true
        - metric: up_price
          operator: ">="
          value: 0.95
      action: sell_up

    - name: take_profit_down_position
      all:
        - metric: has_down_position
          operator: "is"
          value: true
        - metric: down_price
          operator: ">="
          value: 0.95
      action: sell_down

    - name: cheap_up_lottery
      pool: lottery
      all:
        - metric: up_price
          operator: "<="
          value: 0.025
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: "<="
          value: {FLIP_ZONE_DIST_PCT}
      action: buy_up
      token_amount: 25

    - name: cheap_down_lottery
      pool: lottery
      all:
        - metric: down_price
          operator: "<="
          value: 0.025
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: "<="
          value: {FLIP_ZONE_DIST_PCT}
      action: buy_down
      token_amount: 25

    - name: btc_below_price_to_beat_buy_down
      pool: main
      all:
        - metric: btc_below_price_to_beat
          operator: "is"
          value: true
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: ">="
          value: {FLIP_ZONE_DIST_PCT}
        - metric: down_price
          operator: "<="
          value: 0.85
      action: buy_down
      token_amount: 30

    - name: btc_above_price_to_beat_buy_up
      pool: main
      all:
        - metric: btc_above_price_to_beat
          operator: "is"
          value: true
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: ">="
          value: {FLIP_ZONE_DIST_PCT}
        - metric: up_price
          operator: "<="
          value: 0.85
      action: buy_up
      token_amount: 30

    - name: up_price_momentum_chase_buy_up
      pool: main
      all:
        - metric: up_price_pct_change
          operator: ">="
          value: 3
        - metric: up_price
          operator: "<="
          value: 0.85
      action: buy_up
      token_amount: 20

    - name: down_price_momentum_chase_buy_down
      pool: main
      all:
        - metric: down_price_pct_change
          operator: ">="
          value: 3
        - metric: down_price
          operator: "<="
          value: 0.85
      action: buy_down
      token_amount: 30
"""


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    configs = {}
    for split in LOTTERY_SPLITS:
        configs[f"lot{int(split * 100)}"] = build_config(f"lot{int(split * 100)}", split)
    configs[f"lot{int(PER_RULE_VARIANT_SPLIT * 100)}_perrule"] = build_config(
        f"lot{int(PER_RULE_VARIANT_SPLIT * 100)}_perrule", PER_RULE_VARIANT_SPLIT,
        cooldown_scope="per_rule",
    )
    for name, text in configs.items():
        path = OUTPUT_DIR / f"flipzone_{name}.yaml"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
