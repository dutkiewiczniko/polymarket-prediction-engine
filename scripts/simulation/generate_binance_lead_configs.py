"""Generate the Binance-lead lottery configs (binance_lead_lottery experiment).

Mechanism (mission lead #3, first validated analytically 2026-07-14 on the
honest 434-market bench + true outcomes): resolution is Chainlink, Binance
leads it by seconds. A cheap side (<= 0.05) that Binance has ALREADY crossed
past the strike by >= 0.02% is a look-ahead buy: first-touch $1 tickets score
EV +2.18/ticket (63 tickets, 6 wins, 9.5% win rate vs ~4-5% breakeven),
positive in BOTH May (+2.11) and July (+2.33) cohorts -- the only lottery
signal that passes the cohort-consistency check with true outcomes. The old
nearstrike champion rule is 1-win-in-49 and July-negative on honest data.

Caveat: 6 winning events total. The engine backtest (liquidity-aware fills)
and live paper trading are the arbiters.

Uses the btc_binance_distance_to_price_to_beat_pct metric (signed; added to
RuleBasedStrategy 2026-07-14). First-touch is approximated with a
has_*_position is false condition (no re-entry while the ticket is held).

Usage:
    python scripts/simulation/generate_binance_lead_configs.py
"""

from pathlib import Path

OUTPUT_DIR = Path("configs/strategies/binance_lead_lottery")


def build_config(
    name: str,
    price_cap: float,
    min_lead_pct: float,
    first_touch: bool,
    token_amount: float = 25,
    pool_share: float = 0.166667,
    min_seconds_left: float | None = None,
    take_profit: bool = True,
) -> str:
    def side_rule(side: str) -> str:
        op, val = (">=", min_lead_pct) if side == "up" else ("<=", -min_lead_pct)
        first_cond = f"""
        - metric: has_{side}_position
          operator: "is"
          value: false""" if first_touch else ""
        # Resolution is Chainlink -- the laggard feed itself. A Binance cross
        # in the final seconds often never prints on Chainlink before expiry:
        # first-touch tickets at seconds_left<=5 went 0/13 (10s floor keeps
        # 6/7 winners while cutting ~33 burn tickets).
        seconds_cond = f"""
        - metric: seconds_left
          operator: ">="
          value: {min_seconds_left}""" if min_seconds_left is not None else ""
        return f"""
    - name: binlead_{side}_lottery
      pool: lottery
      all:
        - metric: {side}_price
          operator: "<="
          value: {price_cap}
        - metric: btc_binance_distance_to_price_to_beat_pct
          operator: "{op}"
          value: {val}{seconds_cond}{first_cond}
      action: buy_{side}
      token_amount: {token_amount}"""

    take_profit_rules = """
    - name: take_profit_up_position
      all:
        - metric: has_up_position
          operator: "is"
          value: true
        - metric: up_price
          operator: ">="
          value: 0.95
      action: sell_up

    - name: take_profit_down_position
      all:
        - metric: has_down_position
          operator: "is"
          value: true
        - metric: down_price
          operator: ">="
          value: 0.95
      action: sell_down
""" if take_profit else ""

    return f"""name: binance_lead_{name}
type: rule_based
starting_balance: 100
order_usd: 1

# Auto-generated by scripts/simulation/generate_binance_lead_configs.py
# Binance-lead lottery variant '{name}': price cap={price_cap},
# min binance lead past strike={min_lead_pct}%, first_touch={first_touch},
# token_amount={token_amount}, lottery pool share={pool_share},
# min_seconds_left={min_seconds_left}, take_profit={take_profit}

params:
  default_usd_amount: 1
  max_orders: 200
  cooldown_ticks: 3

  pools:
    lottery:
      max_pool_spend_pct: {pool_share}

  rules:{take_profit_rules}{side_rule("up")}
{side_rule("down")}
"""


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    configs = {
        # The analytically-validated cell, first-touch.
        "binlead_p05_l02_first": build_config("p05_l02_first", 0.05, 0.02, True),
        # Repeat-entry control: does re-buying while conditions hold bleed?
        "binlead_p05_l02_repeat": build_config("p05_l02_repeat", 0.05, 0.02, False),
        # Looser lead threshold (EV +1.41 analytically, more tickets).
        "binlead_p05_l01_first": build_config("p05_l01_first", 0.05, 0.01, True),
        # Cheaper cap only (EV +5.67 analytically but n=15, July-negative).
        "binlead_p025_l02_first": build_config("p025_l02_first", 0.025, 0.02, True),
        # Capital-scaled: 150 tokens (~$7.50 at 0.05) per first-touch ticket.
        "binlead_p05_l02_first_t150": build_config(
            "p05_l02_first_t150", 0.05, 0.02, True, token_amount=150, pool_share=0.5
        ),
        # --- v2 (2026-07-14): seconds_left >= 10 gate. Final-seconds Binance
        # crosses often never print on Chainlink (the resolution feed) before
        # expiry: engine v1 bought 98 tickets vs the analytic 63 and the extra
        # late tickets were pure burn (first-touch <=5s: 0/13). ---
        "binlead_p05_l02_first_s10": build_config(
            "p05_l02_first_s10", 0.05, 0.02, True, min_seconds_left=10
        ),
        # Hold to resolution: skip the 0.95 take-profit (its sell haircuts
        # every winner ~5% and cheap-entry holds were better historically).
        "binlead_p05_l02_first_s10_hold": build_config(
            "p05_l02_first_s10_hold", 0.05, 0.02, True, min_seconds_left=10, take_profit=False
        ),
        # Capital-scaled with the time gate.
        "binlead_p05_l02_first_s10_t150": build_config(
            "p05_l02_first_s10_t150", 0.05, 0.02, True, token_amount=150,
            pool_share=0.5, min_seconds_left=10
        ),
        # Looser lead with the time gate.
        "binlead_p05_l01_first_s10": build_config(
            "p05_l01_first_s10", 0.05, 0.01, True, min_seconds_left=10
        ),
    }
    for name, text in configs.items():
        path = OUTPUT_DIR / f"{name}.yaml"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
