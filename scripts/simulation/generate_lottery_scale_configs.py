"""Generate the filtered-lottery capital-scaling sweep (lottery_scale_experiment).

THE HYPOTHESIS (2026-07-14): the old "more lottery budget hurts" result
(lot33 437 < lot17 1079) was measured on the UNFILTERED lottery, where ~80% of
tickets were junk beyond 0.05% of the strike. The nearstrike filter removes the
junk, so the filtered lottery may scale to much larger capital shares. This
directly tests the user's "the ones that catch the cheap lottery flips with a
lot of capital tend to succeed" observation.

Three axes, all lottery-only (no momentum rules, no warmup needed):

  * budget: max_pool_spend_pct of the lottery pool (0.167 baseline / 0.33 /
    0.50 / 1.0), ticket size fixed at 25 tokens. Only binds if fire count x
    ticket size can actually reach the cap.
  * ticket scaling: token_amount scaled proportionally with budget
    (25 per 16.7% share), so the pool drains in the same ~4 max-size fires as
    the baseline. This is the real "a lot of capital per flip" variant.
  * filter grid at baseline budget: distance gate (0.02/0.03/0.05 pct) x
    price cap (0.01/0.025/0.05). Baseline cell is d05_p025.

Baseline replication check: lotscale_b17_t25 is param-identical to
configs/strategies/momentum_metrics_experiment/combos/
combo_capalloc_nearstrike_lottery_only_17.yaml and must reproduce its numbers.

Usage:
    python scripts/simulation/generate_lottery_scale_configs.py
"""

from pathlib import Path

OUTPUT_DIR = Path("configs/strategies/lottery_scale_experiment")

BASE_SHARE = 0.166667  # the validated baseline lottery share
BASE_TICKET = 25


def build_config(
    name: str,
    pool_share: float,
    token_amount: float,
    price_cap: float,
    max_dist_pct: float,
) -> str:
    return f"""name: lottery_scale_{name}
type: rule_based
starting_balance: 100
order_usd: 1

# Auto-generated by scripts/simulation/generate_lottery_scale_configs.py
# Filtered-lottery capital-scaling sweep, variant '{name}'.
# lottery pool share={pool_share}, token_amount={token_amount},
# price cap={price_cap}, abs distance gate={max_dist_pct}%

params:
  default_usd_amount: 1
  max_orders: 200
  cooldown_ticks: 3

  pools:
    lottery:
      max_pool_spend_pct: {pool_share}

  rules:
    - name: take_profit_up_position
      all:
        - metric: has_up_position
          operator: "is"
          value: true
        - metric: up_price
          operator: ">="
          value: 0.95
      action: sell_up

    - name: take_profit_down_position
      all:
        - metric: has_down_position
          operator: "is"
          value: true
        - metric: down_price
          operator: ">="
          value: 0.95
      action: sell_down

    - name: cheap_up_lottery
      pool: lottery
      all:
        - metric: up_price
          operator: "<="
          value: {price_cap}
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: "<="
          value: {max_dist_pct}
      action: buy_up
      token_amount: {token_amount}

    - name: cheap_down_lottery
      pool: lottery
      all:
        - metric: down_price
          operator: "<="
          value: {price_cap}
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: "<="
          value: {max_dist_pct}
      action: buy_down
      token_amount: {token_amount}
"""


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    configs: dict[str, str] = {}

    # --- Budget axis (validated filter d=0.05 p=0.025, ticket fixed at 25) ---
    budget_shares = {"b17": BASE_SHARE, "b33": 0.33, "b50": 0.50, "b100": 1.0}
    for tag, share in budget_shares.items():
        configs[f"lotscale_{tag}_t25"] = build_config(
            f"{tag}_t25", share, BASE_TICKET, price_cap=0.025, max_dist_pct=0.05
        )

    # --- Ticket-scaled variants (token_amount proportional to budget, so the
    # pool still drains in ~the same number of max-size fires as baseline) ---
    for tag, share in budget_shares.items():
        if tag == "b17":
            continue  # identical to lotscale_b17_t25
        ticket = round(BASE_TICKET * share / BASE_SHARE)
        configs[f"lotscale_{tag}_t{ticket}"] = build_config(
            f"{tag}_t{ticket}", share, ticket, price_cap=0.025, max_dist_pct=0.05
        )

    # --- Filter grid at baseline budget/ticket ---
    for dist_tag, dist in {"d02": 0.02, "d03": 0.03, "d05": 0.05}.items():
        for price_tag, price in {"p010": 0.01, "p025": 0.025, "p050": 0.05}.items():
            if dist_tag == "d05" and price_tag == "p025":
                continue  # this cell IS the baseline lotscale_b17_t25
            configs[f"lotgrid_{dist_tag}_{price_tag}"] = build_config(
                f"{dist_tag}_{price_tag}", BASE_SHARE, BASE_TICKET,
                price_cap=price, max_dist_pct=dist,
            )

    for name, text in configs.items():
        path = OUTPUT_DIR / f"{name}.yaml"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    print(f"{len(configs)} configs")


if __name__ == "__main__":
    main()
