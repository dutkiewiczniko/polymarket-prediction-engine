"""Generate capital-allocation sweep configs for a fixed winning window set.

The window search converged on slow_plus_1t = {1t,60s,120s,240s,900s}. That
config splits budget EQUALLY across all pools (each momentum window + lottery
gets 1/(n+1) of effective balance). This script sweeps that allocation instead
of the window set:

  * lottery-share sweep: give the cheap-lottery pool a fraction L of the total,
    split the remaining (1-L) equally across the momentum windows. L=0 removes
    lottery entirely; the equal-split baseline is L = 1/(n+1).
  * weighted-window schemes: split the momentum budget UNEQUALLY across windows
    (e.g. slow/rare windows get a bigger share than fast/frequent ones).

Reuses the window vocabulary, thresholds and rule-pair builder from
generate_momentum_combo_configs.py so the only thing that differs from the
validated combos is the per-pool max_pool_spend_pct (and optionally
cooldown_scope). Emits into the same combos/ dir with a capalloc_ prefix.

Usage:
    python scripts/simulation/generate_capital_allocation_configs.py
"""

from pathlib import Path

from scripts.simulation.generate_momentum_combo_configs import (
    WINDOW_THRESHOLDS,
    momentum_rule_pair,
    window_speed,
)

OUTPUT_DIR = Path("configs/strategies/momentum_metrics_experiment/combos")

# The converged winning window set.
WINNER_WINDOWS = ["1t", "60s", "120s", "240s", "900s"]


def build_config(
    name: str,
    windows: list[str],
    pool_pcts: dict[str, float],
    cooldown_scope: str = "global",
    lottery_max_abs_dist_pct: float | None = None,
) -> str:
    """pool_pcts maps 'lottery' and each 'momentum_<window>' to its
    max_pool_spend_pct (fraction of effective balance).

    IMPORTANT: lottery share 0 removes the lottery RULES entirely, not just the
    budget. A zero-cap pool whose rules stay in the list is a poison pill: the
    first tick where a side trades <= 0.025 (early in strong trends!) matches
    the lottery rule, whose exhausted pool returns a blocking hold -- permanently
    starving every momentum rule below it for the rest of the market. Found the
    hard way in capalloc_screen_3x30 (orders 1950 -> ~370, rewards negative).
    """
    ordered = sorted(windows, key=window_speed, reverse=True)
    include_lottery = pool_pcts["lottery"] > 0

    pool_lines = []
    if include_lottery:
        pool_lines += ["    lottery:", f"      max_pool_spend_pct: {round(pool_pcts['lottery'], 6)}"]
    for window in ordered:
        key = f"momentum_{window}"
        pool_lines.append(f"    {key}:")
        pool_lines.append(f"      max_pool_spend_pct: {round(pool_pcts[key], 6)}")
    pools_block = "\n".join(pool_lines)

    rules_blocks = "\n".join(
        momentum_rule_pair(window, WINDOW_THRESHOLDS[window]) for window in ordered
    )

    scope_line = f"  cooldown_scope: {cooldown_scope}\n" if cooldown_scope != "global" else ""
    alloc_summary = ", ".join(
        f"{k}={round(v, 4)}" for k, v in pool_pcts.items()
    )

    # Near-strike ticket filter (2026-07-12, analyze_lottery_tickets.py over all
    # 320 bench markets): tickets only pay when BTC is within ~0.05% of the
    # strike at purchase (win rate 24%/10% inside 0.02/0.05, ~0% beyond); the
    # filter kept 18/19 winners incl. all OOS-moonshot tickets while cutting
    # ~80% of ticket spend.
    dist_condition = ""
    if lottery_max_abs_dist_pct is not None:
        dist_condition = f"""
        - metric: abs_btc_distance_to_price_to_beat_pct
          operator: "<="
          value: {lottery_max_abs_dist_pct}"""

    lottery_rules = f"""
    - name: cheap_up_lottery
      pool: lottery
      all:
        - metric: up_price
          operator: "<="
          value: 0.025{dist_condition}
      action: buy_up
      token_amount: 25

    - name: cheap_down_lottery
      pool: lottery
      all:
        - metric: down_price
          operator: "<="
          value: 0.025{dist_condition}
      action: buy_down
      token_amount: 25
""" if include_lottery else ""

    return f"""name: momentum_capalloc_{name}
type: rule_based
starting_balance: 100
order_usd: 1

# Auto-generated by scripts/simulation/generate_capital_allocation_configs.py
# Winner window set {WINNER_WINDOWS}, capital-allocation variant '{name}'.
# Pool shares (max_pool_spend_pct of effective balance): {alloc_summary}
# cooldown_scope: {cooldown_scope}

params:
  default_usd_amount: 1
  max_orders: 200
  cooldown_ticks: 3
{scope_line}
  pools:
{pools_block}

  rules:
    - name: take_profit_up_position
      all:
        - metric: has_up_position
          operator: "is"
          value: true
        - metric: up_price
          operator: ">="
          value: 0.95
      action: sell_up

    - name: take_profit_down_position
      all:
        - metric: has_down_position
          operator: "is"
          value: true
        - metric: down_price
          operator: ">="
          value: 0.95
      action: sell_down

{lottery_rules}
{rules_blocks}"""


def lottery_sweep_pcts(windows: list[str], lottery_share: float) -> dict[str, float]:
    """Lottery gets `lottery_share` of total; momentum windows split the rest equally."""
    momentum_each = (1.0 - lottery_share) / len(windows)
    pcts = {"lottery": lottery_share}
    for w in windows:
        pcts[f"momentum_{w}"] = momentum_each
    return pcts


def weighted_window_pcts(
    windows: list[str], lottery_share: float, weights: dict[str, float]
) -> dict[str, float]:
    """Momentum budget (1-lottery_share) split across windows proportional to weights."""
    total_w = sum(weights[w] for w in windows)
    pcts = {"lottery": lottery_share}
    for w in windows:
        pcts[f"momentum_{w}"] = (1.0 - lottery_share) * weights[w] / total_w
    return pcts


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    n = len(WINNER_WINDOWS)
    equal_share = 1.0 / (n + 1)  # baseline lottery share when everything is equal

    configs: dict[str, str] = {}

    # --- Lottery-share sweep (momentum split equally) ---
    # 0%, half-of-equal, equal(baseline), ~2x equal, 50%.
    lottery_shares = {
        "lot0": 0.0,
        "lot8": round(equal_share / 2, 6),
        "lot17_equal": round(equal_share, 6),
        "lot33": 0.33,
        "lot50": 0.50,
    }
    for tag, share in lottery_shares.items():
        configs[f"{tag}"] = build_config(
            tag, WINNER_WINDOWS, lottery_sweep_pcts(WINNER_WINDOWS, share)
        )

    # --- Weighted-window schemes (lottery pinned at the equal share so the ONLY
    # difference vs lot17_equal is how the momentum budget is split) ---
    # slow/rare windows fire less often but with higher conviction; test whether
    # concentrating budget on them beats equal split. fast_heavy is the control.
    schemes = {
        "slowheavy": {"900s": 3, "240s": 2, "120s": 1, "60s": 1, "1t": 1},
        "slowheavy_x": {"900s": 4, "240s": 3, "120s": 2, "60s": 1, "1t": 1},
        "fastheavy": {"900s": 1, "240s": 1, "120s": 1, "60s": 2, "1t": 3},
    }
    for tag, weights in schemes.items():
        configs[f"w_{tag}"] = build_config(
            f"w_{tag}", WINNER_WINDOWS, weighted_window_pcts(WINNER_WINDOWS, equal_share, weights)
        )

    # --- Lottery-only controls (no momentum rules at all) ---
    # lot0 (momentum-only) collapsed to ~10 median while every lottery-carrying
    # config makes 400-939 -- so how much does momentum add on top of JUST the
    # lottery leg? _17 keeps the winner's exact lottery budget; _100 gives the
    # lottery the whole balance.
    configs["lottery_only_17"] = build_config("lottery_only_17", [], {"lottery": equal_share})
    configs["lottery_only_100"] = build_config("lottery_only_100", [], {"lottery": 1.0})

    # --- No-lottery supporter candidates (momentum-only, various window sets;
    # for the "best partner for the near-strike lottery" search) ---
    configs["mom_only_1t_2t_60_120"] = build_config(
        "mom_only_1t_2t_60_120", ["1t", "2t", "60s", "120s"],
        lottery_sweep_pcts(["1t", "2t", "60s", "120s"], 0.0),
    )

    # --- Near-strike-filtered variants (lottery buys gated on BTC being within
    # 0.05% of the strike; see analyze_lottery_tickets.py) ---
    configs["nearstrike_lottery_only_17"] = build_config(
        "nearstrike_lottery_only_17", [], {"lottery": equal_share},
        lottery_max_abs_dist_pct=0.05,
    )
    configs["nearstrike_equal"] = build_config(
        "nearstrike_equal", WINNER_WINDOWS, lottery_sweep_pcts(WINNER_WINDOWS, equal_share),
        lottery_max_abs_dist_pct=0.05,
    )

    for name, text in configs.items():
        path = OUTPUT_DIR / f"combo_capalloc_{name}.yaml"
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
